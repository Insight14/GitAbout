"use client";

import React, { useState } from "react";
import { ProjectDraft } from "@/lib/types";
import { Copy, Check, Download, FileText } from "lucide-react";

interface MarkdownExportProps {
  username: string;
  projects: ProjectDraft[];
}

export function generateMarkdown(username: string, projects: ProjectDraft[]): string {
  const lines: string[] = [];
  lines.push(`# Technical Projects & Experience Draft — @${username}`);
  lines.push(`*Generated by GitAnswer • Evidence-Grounded Resume Drafts*\n`);

  for (const p of projects) {
    lines.push(`## ${p.repo}`);
    lines.push(`**Repository:** ${p.repoUrl}`);
    lines.push(`**Summary:** ${p.summary}\n`);

    lines.push(`### Resume Bullets`);
    for (const b of p.bullets) {
      lines.push(`- ${b.text} *(Evidence: ${b.source})*`);
    }
    lines.push("");

    if (p.skills.length > 0) {
      lines.push(`### Verified Technologies & Skills`);
      lines.push(
        p.skills.map((s) => `- **${s.name}**: verified in \`${s.evidence}\``).join("\n")
      );
      lines.push("");
    }

    if (p.missing_info.length > 0) {
      lines.push(`### Interview Prep Notes (Metrics to Clarify)`);
      for (const q of p.missing_info) {
        lines.push(`- [ ] ${q}`);
      }
      lines.push("");
    }

    lines.push("---\n");
  }

  return lines.join("\n");
}

export function MarkdownExport({ username, projects }: MarkdownExportProps) {
  const [copied, setCopied] = useState(false);

  const handleCopy = () => {
    const md = generateMarkdown(username, projects);
    navigator.clipboard.writeText(md);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleDownload = () => {
    const md = generateMarkdown(username, projects);
    const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${username}-github-resume-drafts.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="flex items-center gap-2">
      <button
        onClick={handleCopy}
        className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-slate-800 text-slate-100 hover:bg-slate-700 border border-slate-700 transition-colors"
      >
        {copied ? (
          <>
            <Check className="w-3.5 h-3.5 text-emerald-400" />
            <span className="text-emerald-300">Copied Markdown!</span>
          </>
        ) : (
          <>
            <Copy className="w-3.5 h-3.5 text-slate-300" />
            <span>Copy as Markdown</span>
          </>
        )}
      </button>

      <button
        onClick={handleDownload}
        className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-slate-900/80 text-slate-300 hover:text-white hover:bg-slate-800 border border-slate-800 transition-colors"
        title="Download .md file"
      >
        <Download className="w-3.5 h-3.5" />
        <span className="hidden sm:inline">Download .md</span>
      </button>
    </div>
  );
}
